// CONTRACT LAYER: matches the backends UserDto / AuthResponse

export type Gender = 'MALE' | 'FEMALE' | 'NON_BINARY';

export interface User {
    id: string;     // "u_1", generated by the backend
    firstName: string;
    lastName: string;
    username: string;   // generated by the backend, ex: "arose1234"
    email: string;
    gender?: Gender;    // frontend only, the backend has no gender, might take out?
}

export interface UpdateProfileRequest {
  firstName: string;
  lastName: string;
  email: string;
  gender?: Gender;
}

export interface LoginRequest {
    identifier: string;     // username or email
    password: string;
}

export interface RegisterRequest {
    firstName: string;
    lastName: string;
    email: string;
    password: string;
}

export interface AuthAccount {
    accountNumber: string;
    balanceCents: number;
    userId: string;
}

export interface AuthResponse {
    user: User;
    account: AuthAccount;
    token: string;
}